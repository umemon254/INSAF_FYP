-- INSAF client reviews
-- A client may leave one review only after their appointment is completed.
create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  appointment_id bigint not null unique references public.appointments(id) on delete cascade,
  lawyer_id uuid not null references auth.users(id) on delete cascade,
  reviewer_id uuid not null references auth.users(id) on delete cascade,
  reviewer_name text not null default 'Client',
  rating smallint not null check (rating between 1 and 5),
  comment text check (comment is null or char_length(comment) <= 1000),
  created_at timestamptz not null default now()
);

create index if not exists reviews_lawyer_created_idx
  on public.reviews (lawyer_id, created_at desc);

create or replace function public.set_review_reviewer_name()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  select coalesce(nullif(p.full_name, ''), 'Client')
    into new.reviewer_name
  from public.profiles p
  where p.id = new.reviewer_id;
  new.reviewer_name := coalesce(new.reviewer_name, 'Client');
  return new;
end;
$$;

drop trigger if exists set_review_reviewer_name on public.reviews;
create trigger set_review_reviewer_name
  before insert on public.reviews
  for each row execute function public.set_review_reviewer_name();

alter table public.reviews enable row level security;

drop policy if exists "authenticated users read reviews" on public.reviews;
create policy "authenticated users read reviews"
  on public.reviews for select to authenticated using (true);

drop policy if exists "client reviews own completed appointment" on public.reviews;
create policy "client reviews own completed appointment"
  on public.reviews for insert to authenticated
  with check (
    reviewer_id = auth.uid()
    and exists (
      select 1 from public.appointments a
      where a.id = appointment_id
        and a.user_id = auth.uid()
        and a.lawyer_id = lawyer_id
        and a.status = 'completed'
    )
  );

revoke all on public.reviews from anon, authenticated;
grant select, insert on public.reviews to authenticated;
grant usage, select on sequence public.reviews_id_seq to authenticated;
