-- INSAF notifications
-- Run once in Supabase SQL Editor. Safe to re-run.
-- Notifications are created by database triggers, never by an untrusted client.

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  appointment_id bigint references public.appointments(id) on delete cascade,
  message text not null,
  link text not null default '/dashboard/notifications',
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists notifications_user_created_idx
  on public.notifications (user_id, created_at desc);
create index if not exists notifications_user_unread_idx
  on public.notifications (user_id, is_read) where is_read = false;

-- If this table was already created manually in the live project, bring it up to
-- the same shape without dropping existing notification records.
alter table public.notifications add column if not exists appointment_id bigint
  references public.appointments(id) on delete cascade;
alter table public.notifications add column if not exists message text;
alter table public.notifications add column if not exists link text not null default '/dashboard/notifications';
alter table public.notifications add column if not exists is_read boolean not null default false;
alter table public.notifications add column if not exists created_at timestamptz not null default now();

alter table public.notifications enable row level security;

drop policy if exists "read own notifications" on public.notifications;
create policy "read own notifications"
  on public.notifications for select to authenticated
  using (user_id = auth.uid());

drop policy if exists "mark own notifications read" on public.notifications;
create policy "mark own notifications read"
  on public.notifications for update to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

-- Clients and lawyers cannot insert or delete notifications directly.
revoke all on public.notifications from anon, authenticated;
grant select, update on public.notifications to authenticated;

create or replace function public.notify_appointment_parties()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.notifications(user_id, appointment_id, message, link)
    values (new.lawyer_id, new.id, 'You received a new appointment request.', '/lawyer/dashboard');
    return new;
  end if;

  if new.status is distinct from old.status then
    if new.status = 'accepted' then
      insert into public.notifications(user_id, appointment_id, message, link)
      values (new.user_id, new.id, 'Your appointment request was accepted.', '/dashboard/appointments');
    elsif new.status = 'rejected' then
      insert into public.notifications(user_id, appointment_id, message, link)
      values (new.user_id, new.id, 'Your appointment request was declined.', '/dashboard/appointments');
    elsif new.status = 'cancelled' then
      if auth.uid() = new.user_id then
        insert into public.notifications(user_id, appointment_id, message, link)
        values (new.lawyer_id, new.id, 'A client cancelled an appointment.', '/lawyer/dashboard');
      else
        insert into public.notifications(user_id, appointment_id, message, link)
        values (new.user_id, new.id, 'Your lawyer cancelled the appointment.', '/dashboard/appointments');
      end if;
    elsif new.status = 'completed' then
      insert into public.notifications(user_id, appointment_id, message, link)
      values (new.user_id, new.id, 'Your appointment was marked completed. You can now leave a review.', '/dashboard/appointments');
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists appointment_notifications on public.appointments;
create trigger appointment_notifications
  after insert or update of status on public.appointments
  for each row execute function public.notify_appointment_parties();
